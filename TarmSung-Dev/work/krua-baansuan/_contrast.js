#!/usr/bin/env node
/* _contrast.js — วัด contrast จริงตาม WCAG 2.1 ไม่ใช่เดาจากค่า L
   ใช้: node _contrast.js   แล้วเอาตัวเลขที่ได้ไปเขียนกำกับใน css/tokens.css
   ENGINE §4 บังคับให้วัด เพราะสีที่ "ดูสว่างพอ" เคยตกเกณฑ์มาแล้ว */
const srgb = (h) => {
  const n = parseInt(h.replace("#", ""), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
};
const lum = (h) => { const [r, g, b] = srgb(h); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

const PAIRS = [
  ["เนื้อความบนพื้นครีม",   "#241C15", "#FBF6EC"],
  ["ข้อความรองบนพื้นครีม",  "#6B5B48", "#FBF6EC"],
  ["ตัวหนังสือบนปุ่มเขียว",  "#FFFFFF", "#2E6B4A"],
  ["ลิงก์เขียวบนพื้นครีม",   "#205238", "#FBF6EC"],
  ["ราคาบนการ์ดขาว",       "#8A5A12", "#FFFFFF"],
  /* แถบมืด #story — เพิ่ม 21/8/26 พร้อมแถบนั้น */
  ["เนื้อความบนไม้เข้ม",     "#FBF6EC", "#241C15"],
  ["ข้อความรองบนไม้เข้ม",    "#C6B49B", "#241C15"],
  ["ทองบนไม้เข้ม",          "#E8B45C", "#241C15"],
  /* ปุ่ม "เก็บ" ในเมนู — เพิ่ม 21/8/26 พร้อมใบออเดอร์ ปุ่มนี้นั่งบนแถบ section--tint
     (wood-100) ตอนปกติ และบน leaf-100 ตอนชี้ ทั้งสองพื้นเป็นคู่ใหม่ที่ไม่เคยวัด */
  ["ปุ่มเก็บบนแถบครีมเข้ม",   "#205238", "#F3EADA"],
  ["ปุ่มเก็บตอนชี้",         "#205238", "#DCEBE0"],
];
let bad = 0;
for (const [name, fg, bg, need = 4.5] of PAIRS) {
  const r = ratio(fg, bg);
  if (r < need) bad++;
  console.log(`${r >= need ? "✓" : "✗"} ${name.padEnd(26)} ${fg} บน ${bg} = ${r.toFixed(2)}:1 (ต้องการ ${need}:1)`);
}
process.exit(bad ? 1 : 0);

-- ใครลบได้
--   แอดมิน            — ใบไหนก็ได้ (ระบบนี้ 1 บริษัท 1 ชุด แอดมินคือคนเก็บกวาดให้ทุกคน)
--   ฝ่ายจัดซื้อ        — เฉพาะใบที่ตัวเองบันทึก เหมือนกติกา update ที่มีอยู่เดิม
--
-- ขอบเขตที่กันไว้
--   ใบที่มีผลตรวจรับแล้วห้ามลบ — ตรวจรับแล้วถือว่าปิดเรื่อง ต้องเหลือร่องรอยไว้
--   บรรทัดจำนวนใน delivery_lines หายตามเองด้วย FK on delete cascade
--   ไฟล์แนบในคลังไม่ถูกลบตาม ตามหลักเดียวกับ db/10_storage.sql
--     (หลักฐานที่เคยแนบต้องตามกลับได้ ถึงใบจะหายไปแล้ว)
--   การลบลง trg_audit ครบ ตามได้ว่าใครลบใบไหนเมื่อไหร่
--
-- รันซ้ำได้
-- ============================================================================

drop policy if exists purchasing_undo on deliveries;
create policy purchasing_undo on deliveries for delete to authenticated
  using ((has_any_role('admin')
          or (has_any_role('purchasing') and recorded_by = auth.uid()))
         and not exists (select 1 from grs g where g.delivery_id = deliveries.id));

  let uiLang = 'en';
  function resolve(pref) {
    if (pref === 'en' || pref === 'th') return pref;
    const loc = (navigator.language || 'en').toLowerCase();
    return loc.startsWith('th') ? 'th' : 'en';
  }
  function t(key) {
    const d = DICT[uiLang] || DICT.en;
    return (key in d) ? d[key] : (DICT.en[key] != null ? DICT.en[key] : key);
  }
  function applyI18n(root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  }
  // Returns true when the language actually changed, so callers know whether to re-render dynamic text.
  function setLang(pref) {
    const next = resolve(pref);
    if (next === uiLang) return false;
    uiLang = next;
    applyI18n();
    return true;
  }
  window.i18n = { t, applyI18n, setLang, get lang() { return uiLang; } };

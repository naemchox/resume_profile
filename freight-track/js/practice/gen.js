function shopName(amp){
  const name = `${pick(PREFIX)}${pick(ROOT)}${pick(SUFFIX)}`;
  return Math.random() < .3 ? `${name} สาขา${amp}` : name;
}

function address(area, [amp, tam, zip]){
  const no = `${rnd(1, 299)}${Math.random() < .3 ? `/${rnd(1, 99)}` : ''}`;
  const moo = !area.bkk && Math.random() < .6 ? ` ม.${rnd(1, 12)}` : '';
  const road = pick(area.roads);
  return area.bkk
    ? `${no} ${road} แขวง${tam} เขต${amp} กรุงเทพฯ ${zip}`
    : `${no}${moo} ${road} ต.${tam} อ.${amp} จ.${area.prov} ${zip}`;
}

/** หนึ่งเที่ยว — 3–7 ร้าน · ร้านละ 1–4 บิล (ส่วนใหญ่ 1–2) · โซนเดียวกันทั้งเที่ยวเหมือนงานจริง */
export function makeTrip(){
  const zone = [pick(AREAS), pick(AREAS)];
  const nShop = rnd(3, 7);
  const used = new Set();
  const stops = [];
  for (let s = 0; s < nShop; s++){
    const area = pick(zone);
    const place = pick(area.list);
    let name = shopName(place[0]);
    while (used.has(name)) name = shopName(place[0]);
    used.add(name);
    const dropoff = { name, address: address(area, place), contact: `คุณ${pick(PEOPLE)}` };
    const nBill = pick([1, 1, 1, 1, 2, 2, 2, 3, 4]);
    for (let b = 0; b < nBill; b++){
      const [goods, unit] = pick(GOODS);
      const pieces = rnd(2, 60);
      stops.push({
        id: uid('bill'),
        shop: name,
        invoice: `${pick(['26', '27'])}${digits(8)}`,
        code: `5370${digits(6)}`,
        weightKg: Math.round(pieces * (rnd(30, 180) / 10) * 10) / 10,
        cargo: `${goods} ${pieces} ${unit}`,
        dropoff,
        status: 'open',          /* open · ok · fail */
        proof: null,
      });
    }
  }
  const now = Date.now();
  return {
    id: uid('trip'),
    code: `7372${digits(6)}`,
    vehicle: `ตัวอย่าง${pick(['กลาง', 'ตวอ', 'ตอ'])}${rnd(1, 6)} ${pick(TRUCKS)}${rnd(1, 3)}คัน`,
    note: Math.random() < .35 ? pick(NOTES) : '',
    step: 'received',            /* received → loaded → departed → delivered (ปิดเที่ยว) */
    stops,
    createdAt: now,
    updatedAt: now,
    events: [{ id: uid('ev'), step: 'received', at: now - rnd(20, 90) * 60000, by: 'ทีมคลังบางนา (จำลอง)', note: 'ตรวจนับครบตามใบแจ้งหนี้ ของพร้อมขึ้นรถ' }],
  };
}
